def stems_for(name):
    """Return prefix stems covering the nominative + oblique cases."""
    if name in EXCEPTIONS:
        return EXCEPTIONS[name]
    soft = "чжшщйїь"
    if name.endswith("ка"):
        return [name[:-1], name[:-2] + "ц"]          # Шепетівк, Шепетівц
    if name.endswith("піль"):
        return [name[:-1], name[:-4] + "пол"]        # Бориспіл, Бориспол
    if name.endswith("інь"):
        return [name[:-1], name[:-3] + "ен"]         # Ірпін, Ірпен
    if name.endswith("ець"):
        return [name, name[:-3] + "ц"]               # Кременець, Кременц
    if name.endswith("їв"):
        return [name, name[:-2] + "єв"]              # Чугуїв, Чугуєв
    if name.endswith("ів"):
        vowel = "ев" if name[-3] in soft else "ов"
        return [name, name[:-2] + vowel]             # Харків→Харков, Бердичів→Бердичев
    if name.endswith("ий"):
        return [name[:-2]]                           # Шептицьк(ий/ого/ому)
    if name.endswith(("а", "я", "е", "о", "и", "ь")):
        return [name[:-1]]                           # Полтав, Коломи, Кам'янськ, Уман
    if name.endswith("к"):
        return [name[:-1]]                           # Кременчу(к/ці), Луць(к/ку)
    return [name]                                    # Калуш, Дрогобич, Ніжин…


APOSTROPHES = "’ʼ`´"             # ’ ʼ ` ´


def normalize(text):
    """Fold apostrophe variants to ASCII ' before matching."""
    for ch in APOSTROPHES:
        text = text.replace(ch, "'")
    return text


def regex_for(stem_list):
    parts = [re.escape(s) for s in stem_list]
    return "|".join(parts)


def match(name, text):
    """Case-sensitive: Буча≠буча, Долина≠долина."""
    return re.search(regex_for(all_stems(name)), normalize(text)) is not None


def all_stems(name):
    row = next(c for c in CITIES if c[0] == name)
    stems = list(stems_for(name))
    for alt in filter(None, row[1].split(",")):
        stems += stems_for(alt.strip())
    return stems


