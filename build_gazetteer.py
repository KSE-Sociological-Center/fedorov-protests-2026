"""
build_gazetteer.py — tiered city gazetteer with declension-safe search stems.

    python build_gazetteer.py [outfile]     # default: gazetteer.csv

Purpose (see prompt.md §4). The run-1 gazetteer sweep (499 cities × 1 Google
News query × name-required-in-headline) cost ~475 queries, got blocked and
found one city. The failure was the METHOD, not the gazetteer: small cities
almost never make headlines — they live as a line inside round-ups,
announcement lists and local Telegram channels. This file supports the cheap
uses of a gazetteer:

  1. GREP filter over already-downloaded page bodies (0 queries) — needs
     stems that survive Ukrainian declension, incl. vowel alternation:
     Ірпінь→в Ірпені, Бориспіль→у Борисполі, Харків→у Харкові.
  2. Batched OR web queries over tier A only (~5 queries instead of 475) —
     use NOMINATIVE names there; search engines inflect on their own.
     Stems are for grep, nominatives are for queries.

Tiers. Tier A = pop ≥ 50k, tier B = 20–49k. Empirical basis: the five cities
we missed vs. the ПошукAI Telegram-monitoring map of 17.07.2026 (Ірпінь,
Бориспіль, Калуш, Дрогобич, Коломия) are ALL ≥ 50k. Even TG monitoring found
nothing in the 20–49k band, so tier B is scan=optional.

Populations, rounded to thousands. Tier A (>=50k): 2020 estimates from the
uk.wikipedia table «Міста України (за населенням)» (supplied by hand,
2026-07-18 — the page is unreachable from the build environment). Tier B
(20-49k): 2022 reference-knowledge estimates, to be reconciled the same way
if the 20-50k block of the table is supplied. Good enough
for tier assignment; two borderline cities (Горішні Плавні, Нововолинськ,
~50k) are kept in tier A deliberately. To refresh from Wikidata:

  SELECT ?cityLabel (MAX(?pop) AS ?population) WHERE {
    ?city wdt:P31/wdt:P279* wd:Q515 ; wdt:P17 wd:Q212 ; wdt:P1082 ?pop .
    FILTER(?pop >= 20000)
    SERVICE wikibase:label { bd:serviceParam wikibase:language "uk". } }
  GROUP BY ?cityLabel ORDER BY DESC(?population)

status: free / frontline / occupied — front line as known at build time
(review before each new event; the occupied list is deliberately coarse and
non-exhaustive since scan=no anyway).

Matching is CASE-SENSITIVE by design: Буча≠буча, Долина≠долина, Ізюм≠ізюм.
Normalize apostrophes before matching (see normalize()). Stems are prefixes:
match with `stem` anywhere in text; false positives are fine at the
candidate stage — a human/agent verifies every hit anyway.
"""

