def selftest():
    ok = True
    for name, text in POSITIVE:
        if not match(name, text):
            print("FAIL positive: %s ∉ «%s» (stems: %s)"
                  % (name, text, all_stems(name)))
            ok = False
    for name, text in NEGATIVE:
        if match(name, text):
            print("FAIL negative: %s ∈ «%s»" % (name, text))
            ok = False
    return ok


